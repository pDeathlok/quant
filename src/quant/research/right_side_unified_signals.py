"""Versioned canonical signal flags for unified right-side model research.

The historical z-skill cache is not a point-in-time replay of the live
detectors: several predicates drifted and the cache suppresses repeated hits
for five trading days.  This module freezes one causal research contract:

* the ten z-skill members reproduce the current live detector predicates and
  minimum-history gates for every row;
* no repeated signal is suppressed;
* B2, B3, Vegas, and triple-volume flags retain the columns consumed by the
  current Web selector's family cache.

All calculations operate on one stock at a time.  A row can depend only on the
current and earlier rows after sorting by trade date.
"""

