def download_stocks(
    stocks: list,
    start_date: str = "20100101",
    end_date: str = None,
    adjust: str = "qfq",
    cache_dir: str = "./data/cache"
):
    """
    串行下载股票数据
    
    Args:
        stocks: 股票列表 [(symbol, name), ...]
        start_date: 开始日期
        end_date: 结束日期
        adjust: 复权方式
        cache_dir: 缓存目录
    """
    if end_date is None:
        end_date = datetime.now().strftime("%Y%m%d")

    print(f"开始下载 {len(stocks)} 只股票数据")
    print(f"日期范围: {start_date} ~ {end_date}")
    print(f"复权方式: {adjust}")
    print("=" * 60)

    success_count = 0
    fail_count = 0
    failed_stocks = []
    total_records = 0

    fetcher = DataFetcher(cache_dir=cache_dir)

    for i, (symbol, name) in enumerate(stocks, 1):
        try:
            print(f"[{i}/{len(stocks)}] 正在下载 {symbol} ({name})...", end=" ")
            df = fetcher.get_stock_daily(
                symbol=symbol,
                start_date=start_date,
                end_date=end_date,
                adjust=adjust
            )
            record_count = len(df)
            total_records += record_count
            success_count += 1
            print(f"✓ 成功 ({record_count} 条)")
        except Exception as e:
            fail_count += 1
            failed_stocks.append((symbol, name, str(e)))
            print(f"✗ 失败: {e}")

    print("=" * 60)
    print(f"\n下载完成!")
    print(f"成功: {success_count} 只股票")
    print(f"失败: {fail_count} 只股票")
    print(f"总数据条数: {total_records:,}")

    if failed_stocks:
        print("\n失败列表 (前10个):")
        for symbol, name, reason in failed_stocks[:10]:
            print(f"  {symbol} ({name}): {reason}")

        if len(failed_stocks) > 10:
            print(f"  ... 还有 {len(failed_stocks) - 10} 个失败")

    # 将数据保存到 stocks 目录
    storage = DataStorage(data_dir="./data/stocks")
    for symbol, name in stocks:
        try:
            df = pd.read_parquet(f"{cache_dir}/{symbol}_{start_date}_{end_date}_{adjust}.parquet")
            storage.save_parquet(df, filename=f"{symbol}")
        except:
            pass

    return success_count, fail_count


def main():
    download_stocks(STOCK_LIST, start_date="20100101")


if __name__ == "__main__":
    main()
