def run_variant(
    daily: pd.DataFrame,
    basic: pd.DataFrame,
    call: pd.DataFrame,
    grid_config: HoldingGridConfig,
    start_date: str,
    end_date: str,
) -> dict:
    backtest_config = ConvertibleBondBacktestConfig(
        start_date=start_date,
        end_date=end_date,
        rebalance="monthly",
        commission_rate=0.0002,
        slippage_rate=0.0002,
        initial_cash=1_000_000.0,
    )
    result = backtest_holding_grid(
        daily=daily,
        basic=basic,
        call=call,
        backtest_config=backtest_config,
        grid_config=grid_config,
    )
    out_dir = OUTPUT_ROOT / f"{grid_config.name}_{start_date}_{end_date}_monthly"
    paths = write_backtest_outputs(result, out_dir)
    summary = dict(result.summary)
    summary.update(
        {
            "variant": grid_config.name,
            "rebalance": "monthly",
            "summary_path": str(paths["summary"]),
            "position_trades_path": str(paths["position_trades"]),
        }
    )
    return summary


def main() -> None:
    daily = pd.read_parquet(DAILY_PATH)
    basic = pd.read_parquet(BASIC_PATH)
    call = pd.read_parquet(CALL_PATH) if CALL_PATH.exists() else pd.DataFrame()
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    jobs = [
        (config, start_date)
        for config in ladder_configs()
        for start_date in ["20200101", "20240101"]
    ]
    summaries: list[dict] = []
    for index, (config, start_date) in enumerate(jobs, start=1):
        print(f"[{index}/{len(jobs)}] {config.name} {start_date}", flush=True)
        summaries.append(
            run_variant(
                daily=daily,
                basic=basic,
                call=call,
                grid_config=config,
                start_date=start_date,
                end_date="20260616",
            )
        )
    summary_frame = pd.DataFrame(summaries)
    summary_path = OUTPUT_ROOT / "iteration_summary.csv"
    summary_frame.to_csv(summary_path, index=False)
    columns = [
        "variant",
        "start_date",
        "total_return",
        "annual_return",
        "max_drawdown",
        "closed_position_trades",
        "position_win_rate",
        "position_profit_factor",
        "average_position_return",
        "median_position_return",
        "average_holding_days",
        "average_exposure",
        "trade_count",
    ]
    ranked = summary_frame.sort_values(
        ["start_date", "total_return", "max_drawdown"],
        ascending=[True, False, False],
    )
    print(
        json.dumps(
            json_safe(
                {
                    "summary_path": str(summary_path),
                    "ranked": ranked[columns].to_dict(orient="records"),
                }
            ),
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
